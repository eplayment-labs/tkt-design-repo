type Seed = Omit<TktEvent, "accent" | "sales" | "checkedIn"> & { checkedIn?: number; salesDays?: number };

function build(e: Seed, i: number): TktEvent {
  const { salesDays = 30, checkedIn = 0, ...rest } = e;
  return {
    ...rest,
    accent: accentFor(e.cover),
    checkedIn,
    sales: e.status === "draft" ? [] : salesCurve(e.tiers, salesDays, i + 7),
  };
}


const accentFor = (p: Photo) => ((accents as Record<string, EventAccent | null>)[p.id] ?? null);

/** Deterministic pseudo-random, so server and client render the same data. */
export function seeded(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 2 ** 32;
  };
}

/** Daily sales leading up to `daysAgoEnd`, shaped like a real launch: spike, lull, late push. */
function salesCurve(tiers: Tier[], days: number, seed: number): SalesPoint[] {
  const rand = seeded(seed);
  const sold = tiers.reduce((n, t) => n + t.sold, 0);
  const avg = sold ? tiers.reduce((n, t) => n + t.sold * t.price, 0) / sold : 0;
  const w = Array.from({ length: days }, (_, i) => {
    const x = i / Math.max(1, days - 1);
    return (x < 0.1 ? 4 : 1) + 2.5 * x ** 3 + rand() * 0.6;
  });
  const sum = w.reduce((a, b) => a + b, 0);
  let left = sold;
  return w.map((wi, i) => {
    const n = i === days - 1 ? left : Math.min(left, Math.round((wi / sum) * sold));
    left -= n;
    return { day: at(i - days + 1, "12:00"), sold: n, gross: Math.round((n * avg) / 100) * 100 };
  });
}

